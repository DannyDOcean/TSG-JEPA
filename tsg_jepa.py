# CELL 14 — Component sensitivity diagnostics
# OOD validation only; no retraining
# =============================================================
DIAGNOSTIC_SAMPLES = 2000


def _identity_forward(self, x):
    return x


def _circular_forward(self, x):
    return self.conv_circ(x)


def _reflection_forward(self, x):
    return self.conv_ref(x)


def _mean_only_pool(self, fmap):
    mean = fmap.mean(dim=(2, 3))

    # Repeat mean to preserve the trained projection's
    # expected input dimensions.
    return torch.cat([mean, mean, mean], dim=1)


def run_component_diagnostics():
    indices = np.random.RandomState(
        ANALYSIS_SEED
    ).choice(
        len(ood_val_ds),
        min(DIAGNOSTIC_SAMPLES, len(ood_val_ds)),
        replace=False,
    )

    variants = [
        (
            "baseline",
            "Learned model — single view",
        ),
        (
            "circular",
            "Circular branch only",
        ),
        (
            "reflection",
            "Reflection branch only",
        ),
        (
            "half",
            "50/50 branch blend",
        ),
        (
            "no_gate",
            "Spike gates bypassed",
        ),
        (
            "no_se",
            "SE bypassed with identity",
        ),
        (
            "mean_pool",
            "Mean repeated into all pooling branches",
        ),
    ]

    if FINAL_USE_TTA:
        variants.append(
            (
                "tta",
                "Learned model — 16-view TTA",
            )
        )

    rows = []
    arrays = {"subset_indices": indices}
    original_labels = None

    for key, label in variants:
        probe = copy.deepcopy(clf_model).eval()
        probe.requires_grad_(False)
        started = time.time()

        try:
            for module in probe.modules():
                if isinstance(module, TConvHybrid):
                    if key == "circular":
                        module.forward = types.MethodType(
                            _circular_forward,
                            module,
                        )

                    elif key == "reflection":
                        module.forward = types.MethodType(
                            _reflection_forward,
                            module,
                        )

                    elif key == "half":
                        with torch.no_grad():
                            module.alpha.zero_()

                if (
                    key == "no_gate"
                    and isinstance(module, SpikeGateV2)
                ):
                    module.forward = types.MethodType(
                        _identity_forward,
                        module,
                    )

                if (
                    key == "no_se"
                    and isinstance(module, SqueezeExcite)
                ):
                    module.forward = types.MethodType(
                        _identity_forward,
                        module,
                    )

            if key == "mean_pool":
                probe.encoder.multi_scale_pool = (
                    types.MethodType(
                        _mean_only_pool,
                        probe.encoder,
                    )
                )

            logits, labels = collect_logits(
                probe,
                analysis_loader(ood_val_ds, indices),
                label,
                use_tta=(key == "tta"),
                strong=FINAL_STRONG_TTA,
            )

            trues = labels.numpy()

            if original_labels is None:
                original_labels = trues.copy()
                arrays["labels"] = original_labels

            elif not np.array_equal(
                trues, original_labels
            ):
                raise ValueError(
                    "Diagnostic samples changed "
                    "between variants."
                )

            preds = logits.argmax(1).numpy()

            # Binary logit margin preserves ranking
            # without softmax saturation.
            scores = (
                logits[:, 1] - logits[:, 0]
            ).numpy()

            rows.append({
                "variant": label,
                "n": int(len(trues)),
                "acc": float(
                    accuracy_score(trues, preds)
                ),
                "auc": float(
                    roc_auc_score(trues, scores)
                ),
                "seconds": round(
                    time.time() - started,
                    1,
                ),
            })

            arrays[f"{key}_preds"] = preds
            arrays[f"{key}_scores"] = scores

        finally:
            del probe
            gc.collect()

            if device.type == "cuda":
                torch.cuda.empty_cache()

    table = pd.DataFrame(rows)

    table["delta_acc"] = (
        table["acc"] - table.loc[0, "acc"]
    )

    table["delta_auc"] = (
        table["auc"] - table.loc[0, "auc"]
    )

    table.to_csv(
        analysis_dir / "component_sensitivity.csv",
        index=False,
    )

    np.savez_compressed(
        analysis_dir /
        "component_sensitivity_predictions.npz",
        **arrays,
    )

    with open(
        analysis_dir / "component_sensitivity.json",
        "w",
    ) as f:
        json.dump(
            {
                "training_seed_declared": int(cfg.seed),
                "sampling_seed": ANALYSIS_SEED,
                "checkpoint_sha256": checkpoint_sha256,
                "split": "ood_val",
                "diagnostic_sample_size": int(
                    len(indices)
                ),
                "retraining": False,
                "prediction_rule": (
                    "argmax; no threshold fitting "
                    "for diagnostic variants"
                ),
                "structural_probe_tta": False,
                "tta_comparison_views": (
                    16 if FINAL_USE_TTA else 0
                ),
                "auc_score": (
                    "tumour minus normal logit"
                ),
                "limitations": [
                    (
                        "Post-training sensitivity does "
                        "not establish benefit from "
                        "training with a component."
                    ),
                    (
                        "Circular and reflection branches "
                        "have different learned weights; "
                        "this does not isolate padding alone."
                    ),
                    (
                        "Small sampled differences are not "
                        "evidence of statistical significance."
                    ),
                ],
                "results": table.to_dict(
                    orient="records"
                ),
            },
            f,
            indent=2,
        )

    display(table)

    print(
        "Negative deltas indicate lower performance "
        "after that intervention."
    )

    print(
        "True architecture ablations require separately "
        "trained variants with matched protocols and seeds."
    )

    print(
        f"Saved diagnostics to {analysis_dir}"
    )


run_component_diagnostics()

