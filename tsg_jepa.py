def focal_loss_fn(logits, y, gamma=1.5):
    ce = F.cross_entropy(logits, y, reduction="none", label_smoothing=cfg.label_smooth)
    return ((1.0 - torch.exp(-ce)) ** gamma * ce).mean()


def d4_transform(x, k):
    if k >= 4:
        x = torch.flip(x, dims=[3])
    rot = k % 4
    return torch.rot90(x, rot, dims=[2, 3]) if rot > 0 else x


def equivariance_loss(model, x):
    k = random.randint(1, 7)
    p_o = F.log_softmax(model(x), dim=-1)
    p_t = F.log_softmax(model(d4_transform(x, k)), dim=-1)
    return 0.5 * (F.kl_div(p_o, p_t, reduction="batchmean", log_target=True)
                  + F.kl_div(p_t, p_o, reduction="batchmean", log_target=True))


def anchor_pull_loss(z, y, anchors, margin=0.3):
    z_n = F.normalize(z, dim=-1)
    a_n = F.normalize(anchors, dim=-1)
    sims = z_n @ a_n.t()
    pull = (1.0 - sims.gather(1, y.unsqueeze(1)).squeeze(1)).mean()
    push = F.relu(sims.gather(1, (1 - y).unsqueeze(1)).squeeze(1) - (1.0 - margin)).mean()
    sep = F.relu((a_n[0] * a_n[1]).sum().abs() - margin)
    return pull + push + 0.5 * sep


class SAM:
    def __init__(self, base_optimizer, rho=0.05):
        self.base_optimizer = base_optimizer
        self.rho = rho
        self.param_groups = base_optimizer.param_groups
        self.state = base_optimizer.state
        self._e_ws = {}

    @torch.no_grad()
    def first_step(self):
        norm = torch.norm(torch.stack([p.grad.norm(p=2) for g in self.param_groups
                                         for p in g["params"] if p.grad is not None]), p=2)
        scale = self.rho / (norm + 1e-12)
        for g in self.param_groups:
            for p in g["params"]:
                if p.grad is None:
                    continue
                e_w = p.grad * scale.to(p)
                p.add_(e_w)
                self._e_ws[id(p)] = e_w

    @torch.no_grad()
    def second_step(self):
        for g in self.param_groups:
            for p in g["params"]:
                if id(p) in self._e_ws:
                    p.sub_(self._e_ws[id(p)])
        self._e_ws.clear()
        self.base_optimizer.step()

    def zero_grad(self, set_to_none=True):
        self.base_optimizer.zero_grad(set_to_none=set_to_none)


class ModelEMA:
    def __init__(self, model, decay=0.9995):
        self.decay = decay
        self.shadow = {k: v.detach().cpu().clone().float()
                       for k, v in model.state_dict().items() if v.dtype.is_floating_point}

    @torch.no_grad()
    def update(self, model):
        for k, v in model.state_dict().items():
            if k in self.shadow:
                self.shadow[k] = self.shadow[k].to('cpu').float().mul_(self.decay).add_(v.detach().cpu().float(), alpha=1.0 - self.decay)

    def apply_to(self, model):
        target = model.state_dict()
        cast = {k: v.to(target[k].dtype).to(target[k].device)
                for k, v in self.shadow.items() if k in target}
        full = {k: cast.get(k, target[k]) for k in target}
        model.load_state_dict(full)


class MultiScaleClassifier(nn.Module):
    def __init__(self, encoder, latent, num_classes=2, drop=0.30, use_anchors=True):
        super().__init__()
        self.encoder = encoder
        self.head = nn.Sequential(
            nn.Linear(latent, latent // 2), nn.GELU(), nn.Dropout(drop),
            nn.Linear(latent // 2, latent // 4), nn.GELU(), nn.Dropout(drop * 0.7),
            nn.Linear(latent // 4, num_classes))
        self.use_anchors = use_anchors
        if use_anchors:
            a = F.normalize(torch.randn(num_classes, latent), dim=-1)
            a[1] = F.normalize(a[1] - (a[1] * a[0]).sum() * a[0], dim=-1)
            self.anchors = nn.Parameter(a)

    def forward(self, x, return_z=False):
        fmap = self.encoder.features(x)
        z = self.encoder.pooled(fmap)
        logits = self.head(z)
        return (logits, z) if return_z else logits


