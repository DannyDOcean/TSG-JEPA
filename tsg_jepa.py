def gn(ch, g=8):
    while g > 1 and ch % g:
        g //= 2
    return nn.GroupNorm(g, ch)


def cos_sched(base, final, step, total, warmup=0):
    if step < warmup:
        return base * (step + 1) / max(1, warmup)
    p = min(max((step - warmup) / max(1, total - warmup), 0.0), 1.0)
    return final + 0.5 * (base - final) * (1.0 + math.cos(math.pi * p))


def two_stage_ema(step, total, fast=0.99, slow=0.9995, switch=0.30):
    sw = int(total * switch)
    if step < sw:
        return fast
    p = min(max((step - sw) / max(1, total - sw), 0.0), 1.0)
    return fast + 0.5 * (slow - fast) * (1.0 + math.cos(math.pi * (1.0 - p)))


