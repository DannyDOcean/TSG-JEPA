class SpatialPredictor(nn.Module):
    def __init__(self, ch, depth, drop=0.1):
        super().__init__()
        neck = max(ch // 2, 64)
        layers = [nn.Conv2d(ch, neck, 1, bias=False), gn(neck), nn.GELU()]
        for _ in range(depth - 1):
            layers += [TConvPure(neck, neck, 3, 1, g=neck), gn(neck),
                       nn.GELU(), nn.Dropout2d(drop)]
        layers.append(nn.Conv2d(neck, ch, 1, bias=False))
        self.net = nn.Sequential(*layers)

    def forward(self, x):
        return self.net(x)


class SSLProjector(nn.Module):
    def __init__(self, latent):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(latent, latent, bias=False),
            nn.BatchNorm1d(latent),
            nn.GELU(),
            nn.Linear(latent, latent, bias=False),
        )

    def forward(self, x):
        return self.net(x)


def spatial_loss(pred, tgt, mask):
    p = F.normalize(pred, dim=1)
    t = F.normalize(tgt.detach(), dim=1)
    err = (1.0 - (p * t).sum(dim=1, keepdim=True)) * mask
    return err.sum() / mask.sum().clamp_min(1)


def vicreg_var_loss(z):
    z = z - z.mean(0, keepdim=True)
    std = (z.var(0) + 1e-4).sqrt()
    return F.relu(1.0 - std).mean()


def local_global_loss(z_local, z_global):
    p = F.normalize(z_local, dim=-1)
    t = F.normalize(z_global.detach(), dim=-1)
    return (1.0 - (p * t).sum(-1)).mean()


class TSJEPA(nn.Module):
    def __init__(self, c):
        super().__init__()
        self.c = c
        self.online = Encoder(c)
        self.target = Encoder(c)
        self.pred = SpatialPredictor(c.width, c.pred_depth, c.block_drop)
        self.ssl_proj_online = SSLProjector(c.latent)
        self.ssl_proj_target = SSLProjector(c.latent)
        self.masker = Masker(c.mask_ratio, c.min_blk, c.max_blk, FMAP_H, FMAP_W)
        self.target.load_state_dict(copy.deepcopy(self.online.state_dict()))
        self.ssl_proj_target.load_state_dict(copy.deepcopy(self.ssl_proj_online.state_dict()))
        for p in self.target.parameters():
            p.requires_grad_(False)
        for p in self.ssl_proj_target.parameters():
            p.requires_grad_(False)
        self.ema_d = c.ema_fast

    @torch.no_grad()
    def ema_step(self, step, total):
        self.ema_d = two_stage_ema(step, total, self.c.ema_fast, self.c.ema_slow, self.c.ema_switch_frac)
        for o, t in zip(self.online.parameters(), self.target.parameters()):
            t.data.mul_(self.ema_d).add_(o.data, alpha=1.0 - self.ema_d)
        for o, t in zip(self.ssl_proj_online.parameters(), self.ssl_proj_target.parameters()):
            t.data.mul_(self.ema_d).add_(o.data, alpha=1.0 - self.ema_d)

    def forward(self, x_ctx, x_tgt, x_locals):
        B = x_ctx.size(0)
        with torch.no_grad():
            tgt_fmap = self.target.features(x_tgt)
            _, z_tgt_raw = self.target(x_tgt)
            z_tgt = self.ssl_proj_target(z_tgt_raw)
        mask = self.masker(B, x_ctx.device)
        ctx_fmap, z_ctx_raw = self.online(x_ctx, mask)
        z_ctx = self.ssl_proj_online(z_ctx_raw)
        l_sp = spatial_loss(self.pred(ctx_fmap), tgt_fmap, mask)

        n = x_locals.size(1)
        x_locals_flat = x_locals.view(B * n, *x_locals.shape[2:])
        _, z_locals_raw = self.online(x_locals_flat)
        z_locals = self.ssl_proj_online(z_locals_raw)
        z_tgt_rep = z_tgt.unsqueeze(1).expand(-1, n, -1).reshape(B * n, -1)
        l_local = local_global_loss(z_locals, z_tgt_rep)

        l_var = vicreg_var_loss(z_ctx)
        fr = self.online.spike_stats()
        l_fr = (fr - self.c.target_fr) ** 2

        total = (self.c.lam_spatial * l_sp + self.c.lam_local * l_local
                 + self.c.lam_var * l_var + self.c.lam_fr * l_fr)
        return total, l_sp, l_local, l_var, fr, mask.mean()


