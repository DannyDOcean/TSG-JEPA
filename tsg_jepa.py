class RandomRot90:
    def __call__(self, img):
        k = random.randint(0, 3)
        return img if k == 0 else TF.rotate(img, k * 90)


class GaussianNoise:
    def __init__(self, std=0.015, p=0.2):
        self.std, self.p = std, p
    def __call__(self, x):
        if random.random() > self.p:
            return x
        return (x + torch.randn_like(x) * self.std).clamp(0.0, 1.0)


class StainJitter:
    def __init__(self, sm=0.15, sa=0.05, p=0.6):
        self.sm, self.sa, self.p = sm, sa, p
    def __call__(self, x):
        if random.random() > self.p:
            return x
        mul = 1.0 + torch.randn(3, 1, 1, device=x.device) * self.sm
        add = torch.randn(3, 1, 1, device=x.device) * self.sa
        return (x * mul + add).clamp(0.0, 1.0)


def _build_tf(crop_size, scale, jitter_p=0.8, stain=(0.18, 0.07, 0.7),
              noise=(0.015, 0.20), erase=False):
    s = cfg.stain_jitter_strength
    stain_boosted = (stain[0] * s, stain[1] * s, stain[2])
    ops = [
        transforms.RandomResizedCrop(crop_size, scale=scale, interpolation=Image.BICUBIC),
        transforms.RandomHorizontalFlip(),
        transforms.RandomVerticalFlip(),
        RandomRot90(),
        transforms.RandomApply([transforms.ColorJitter(0.50, 0.50, 0.30, 0.08)], p=jitter_p),
        transforms.ToTensor(),
        StainJitter(*stain_boosted),
        GaussianNoise(*noise),
        transforms.Normalize(MU, SIG),
    ]
    if erase:
        ops.append(transforms.RandomErasing(p=0.25, scale=(0.02, 0.15), ratio=(0.3, 3.3)))
    return transforms.Compose(ops)


