@torch.inference_mode()
def extract(enc, dl):
    enc.eval()
    fs, ys = [], []
    for x, y in dl:
        x = x.to(device, non_blocking=True).contiguous(memory_format=torch.channels_last)
        fs.append(enc.multi_scale_pool(enc.features(x)).cpu())
        ys.append(y)
    return torch.cat(fs), torch.cat(ys)


@torch.inference_mode()
def knn_eval(trx, try_, tex, tey, k=20):
    trx = F.normalize(trx, dim=-1)
    tex = F.normalize(tex, dim=-1)
    sims = tex @ trx.T
    topk_idx = sims.topk(min(k, trx.size(0)), dim=1).indices
    neighbour_labels = try_[topk_idx]
    pred = (neighbour_labels.float().mean(dim=1) >= 0.5).long()
    return (pred == tey).float().mean().item()


def tta_logits(clf_model, x, strong=False):
    base = []
    for k in range(4):
        xr = torch.rot90(x, k, dims=[2, 3])
        base.append(clf_model(xr))
        base.append(clf_model(torch.flip(xr, dims=[3])))
    if not strong:
        return torch.stack(base, dim=0).mean(0)
    H, W = x.shape[-2:]
    H2, W2 = int(H * 1.1), int(W * 1.1)
    x_zoom = F.interpolate(x, size=(H2, W2), mode='bilinear', align_corners=False)
    top, left = (H2 - H) // 2, (W2 - W) // 2
    x_zoom = x_zoom[..., top:top + H, left:left + W]
    zoom = []
    for k in range(4):
        xr = torch.rot90(x_zoom, k, dims=[2, 3])
        zoom.append(clf_model(xr))
        zoom.append(clf_model(torch.flip(xr, dims=[3])))
    return torch.stack(base + zoom, dim=0).mean(0)


def infer_classifier(clf_model, dl, use_tta=False, strong=False):
    clf_model.eval()
    all_logits, all_true = [], []
    with torch.inference_mode():
        for x, y in dl:
            x = x.to(device, non_blocking=True).contiguous(memory_format=torch.channels_last)
            lg = tta_logits(clf_model, x, strong=strong) if use_tta else clf_model(x)
            all_logits.append(lg.cpu())
            all_true.append(y)
    logits = torch.cat(all_logits)
    trues = torch.cat(all_true)
    return logits.argmax(1).numpy(), trues.numpy(), torch.softmax(logits, dim=1)[:, 1].numpy()


