class TConvHybrid(nn.Module):
    def __init__(self, ci, co, k=3, s=1, g=1, blend_init=2.2):
        super().__init__()
        p = k // 2
        self.conv_circ = nn.Conv2d(ci, co, k, s, p, groups=g, padding_mode="circular", bias=False)
        self.conv_ref = nn.Conv2d(ci, co, k, s, p, groups=g, padding_mode="reflect", bias=False)
        nn.init.kaiming_normal_(self.conv_circ.weight, nonlinearity="relu")
        with torch.no_grad():
            self.conv_ref.weight.copy_(self.conv_circ.weight)
        self.alpha = nn.Parameter(torch.tensor(blend_init))

    def forward(self, x):
        a = torch.sigmoid(self.alpha)
        return a * self.conv_circ(x) + (1 - a) * self.conv_ref(x)


class TConvPure(nn.Module):
    def __init__(self, ci, co, k=3, s=1, g=1):
        super().__init__()
        self.conv = nn.Conv2d(ci, co, k, s, k // 2, groups=g, padding_mode="circular", bias=False)
        nn.init.kaiming_normal_(self.conv.weight, nonlinearity="relu")

    def forward(self, x):
        return self.conv(x)


class Stem(nn.Module):
    def __init__(self, c):
        super().__init__()
        w = c.width
        sk = dict(tau=c.tau, vth=c.vth, steps=c.spike_steps,
                  floor=c.gate_floor, beta_init=c.gate_beta_init)
        self.layers = nn.Sequential(
            TConvHybrid(c.in_ch, w // 4, 3, 2, blend_init=c.toroidal_blend_init),
            gn(w // 4), nn.GELU(), SpikeGateV2(w // 4, **sk),
            TConvHybrid(w // 4, w // 2, 3, 2, blend_init=c.toroidal_blend_init),
            gn(w // 2), nn.GELU(), SpikeGateV2(w // 2, **sk),
            TConvHybrid(w // 2, w, 3, 1, blend_init=c.toroidal_blend_init),
            gn(w), nn.GELU(), SpikeGateV2(w, **sk),
        )

    def forward(self, x):
        return self.layers(x)


class BottleneckBlock(nn.Module):
    def __init__(self, ch, hid, c, dp_p=0.0):
        super().__init__()
        sk = dict(tau=c.tau, vth=c.vth, steps=c.spike_steps,
                  floor=c.gate_floor, beta_init=c.gate_beta_init)
        groups = max(1, hid // c.conv_groups_div)
        while groups > 1 and hid % groups != 0:
            groups -= 1
        self.conv1 = nn.Conv2d(ch, hid, 1, bias=False)
        self.norm1 = gn(hid)
        self.gate1 = SpikeGateV2(hid, **sk)
        self.conv2 = TConvHybrid(hid, hid, 3, 1, g=groups, blend_init=c.toroidal_blend_init)
        self.norm2 = gn(hid)
        self.gate2 = SpikeGateV2(hid, **sk)
        self.se = SqueezeExcite(hid, c.se_ratio)
        self.drop = nn.Dropout2d(c.block_drop)
        self.conv3 = nn.Conv2d(hid, ch, 1, bias=False)
        self.norm3 = gn(ch)
        self.gamma = nn.Parameter(torch.ones(1, ch, 1, 1) * c.gamma_init)
        self.dp = DropPath(dp_p)

    def forward(self, x, mask=None):
        r = x
        x = self.gate1(F.gelu(self.norm1(self.conv1(x))))
        x = self.gate2(F.gelu(self.norm2(self.conv2(x))))
        x = self.drop(self.se(x))
        x = self.dp(self.gamma * self.norm3(self.conv3(x)))
        out = F.gelu(r + x)
        if mask is not None and mask.shape[-2:] == out.shape[-2:]:
            out = out * (1.0 - mask)
        return out


class Encoder(nn.Module):
    def __init__(self, c):
        super().__init__()
        w = c.width
        h = int(c.width * c.mlp_ratio)
        self.stem = Stem(c)
        dp_rates = [c.drop_path * i / max(1, c.depth - 1) for i in range(c.depth)] if c.depth > 1 else [0.0]
        self.blocks = nn.ModuleList([BottleneckBlock(w, h, c, dp_p=dp_rates[i]) for i in range(c.depth)])
        self.head = nn.Sequential(nn.Conv2d(w, w, 1, bias=False), gn(w),
                                   nn.GELU(), nn.Dropout2d(c.block_drop))
        self.proj = nn.Sequential(nn.Linear(w * 3, c.latent), nn.LayerNorm(c.latent))

    def features(self, x, mask=None):
        x = self.stem(x)
        if mask is not None and mask.shape[-2:] == x.shape[-2:]:
            x = x * (1.0 - mask)
        for blk in self.blocks:
            x = blk(x, mask)
        return self.head(x)

    def multi_scale_pool(self, fmap):
        z_mean = fmap.mean(dim=[2, 3])
        z_max = fmap.amax(dim=[2, 3])
        scores = fmap.norm(dim=1, keepdim=True)
        weights = F.softmax(scores.flatten(2), dim=-1)
        z_attn = (fmap.flatten(2) * weights).sum(-1)
        return torch.cat([z_mean, z_max, z_attn], dim=1)

    def pooled(self, fmap):
        return self.proj(self.multi_scale_pool(fmap))

    def forward(self, x, mask=None):
        fmap = self.features(x, mask)
        return fmap, self.pooled(fmap)

    def spike_stats(self):
        rates = [m.fr for m in self.modules() if isinstance(m, SpikeGateV2) and m.fr is not None]
        if not rates:
            return torch.tensor(0.0, device=next(self.parameters()).device)
        return torch.stack(rates).mean()


class Masker:
    def __init__(self, ratio, mn, mx, fmap_h=24, fmap_w=24, cache=2048):
        target = int(round(fmap_h * fmap_w * ratio))
        masks = torch.zeros(cache, 1, fmap_h, fmap_w)
        for i in range(cache):
            m = masks[i, 0]
            while m.sum() < target:
                bh, bw = random.randint(mn, mx), random.randint(mn, mx)
                top, left = random.randint(0, fmap_h - 1), random.randint(0, fmap_w - 1)
                rows = (torch.arange(bh) + top) % fmap_h
                cols = (torch.arange(bw) + left) % fmap_w
                m[rows[:, None], cols[None, :]] = 1.0
        self.masks = masks
        self.cache = cache

    def __call__(self, B, dev):
        idx = torch.randint(0, self.cache, (B,))
        return self.masks[idx].to(device=dev, non_blocking=True)


