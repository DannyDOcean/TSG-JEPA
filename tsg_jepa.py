def ssl_train(cfg):
    out = Path(cfg.out_dir)
    opt = torch.optim.AdamW(model.parameters(), lr=cfg.lr, weight_decay=cfg.wd)
    scaler = torch.amp.GradScaler("cuda", enabled=(cfg.use_amp and device.type == "cuda"))

    spe = len(ssl_dl)
    total_steps = cfg.ssl_epochs * spe
    warmup = cfg.warmup_epochs * spe
    step = 0
    best_knn = -1.0
    patience = cfg.ssl_patience
    logs = {k: [] for k in ["epoch", "loss", "spatial", "local", "var", "fr", "ema", "lr", "knn", "knn_id"]}

    resume_path = out / "ssl_resume.pt"
    start_ep = 0
    if resume_path.exists():
        try:
            ckpt = torch.load(resume_path, map_location=device)
            model.online.load_state_dict(ckpt["online"])
            model.target.load_state_dict(ckpt["target"])
            opt.load_state_dict(ckpt["optimizer"])
            scaler.load_state_dict(ckpt["scaler"])
            start_ep = ckpt["epoch"] + 1
            step = ckpt["step"]
            best_knn = ckpt["best_knn"]
            patience = ckpt["patience_left"]
            model.ema_d = ckpt["ema_d"]
            logs_p = out / "ssl_logs.json"
            if logs_p.exists():
                with open(logs_p) as f:
                    logs = json.load(f)
                if "knn_id" not in logs:
                    logs["knn_id"] = []
            print(f"Resumed at epoch {start_ep}, best_knn={best_knn:.4f}")
        except Exception as e:
            print(f"Resume failed: {e}")
            start_ep = 0

    for ep in range(start_ep, cfg.ssl_epochs):
        model.train()
        sums = {k: 0.0 for k in ["loss", "sp", "loc", "var", "fr"]}
        seen = 0
        t0 = time.time()
        pbar = tqdm(ssl_dl, desc=f"SSL {ep+1}/{cfg.ssl_epochs}")
        for batch_i, (x_c, x_t, x_locs) in enumerate(pbar):
            x_c = x_c.to(device, non_blocking=True).contiguous(memory_format=torch.channels_last)
            x_t = x_t.to(device, non_blocking=True).contiguous(memory_format=torch.channels_last)
            x_locs = x_locs.to(device, non_blocking=True)
            bs = x_c.size(0)

            lr = cos_sched(cfg.lr, 1e-6, step, total_steps, warmup)
            for g in opt.param_groups:
                g["lr"] = lr

            opt.zero_grad(set_to_none=True)
            with torch.autocast(device_type=device.type, enabled=cfg.use_amp):
                loss, l_sp, l_loc, l_var, fr, _ = model(x_c, x_t, x_locs)
            scaler.scale(loss).backward()
            scaler.unscale_(opt)
            nn.utils.clip_grad_norm_(model.parameters(), cfg.grad_clip)
            scaler.step(opt)
            scaler.update()
            model.ema_step(step, total_steps)

            for k, v in zip(["loss", "sp", "loc", "var", "fr"],
                             [loss, l_sp, l_loc, l_var, fr]):
                sums[k] += v.detach().item() * bs
            seen += bs
            step += 1
            if batch_i % 50 == 0:
                pbar.set_postfix(loss=f"{loss.item():.3f}", ema=f"{model.ema_d:.4f}")

        em = {k: v / seen for k, v in sums.items()}
        elapsed = time.time() - t0

        logs["epoch"].append(ep)
        for k_log, k_em in [("loss", "loss"), ("spatial", "sp"), ("local", "loc"),
                              ("var", "var"), ("fr", "fr")]:
            logs[k_log].append(em[k_em])
        logs["ema"].append(model.ema_d)
        logs["lr"].append(lr)

        print(f"[SSL {ep+1:02d}] loss={em['loss']:.4f} sp={em['sp']:.4f} "
              f"loc={em['loc']:.4f} fr={em['fr']:.4f} ema={model.ema_d:.4f} | {elapsed:.0f}s")

        knn_ood = None
        knn_id = None
        if (ep + 1) % cfg.eval_every == 0 or ep == cfg.ssl_epochs - 1:
            knn_ood, knn_id, _ = ssl_eval(model, f"ep={ep+1}")
            if knn_ood > best_knn:
                best_knn = knn_ood
                patience = cfg.ssl_patience
                torch.save(model.online.state_dict(), out / "best_ssl_encoder.pt")
                print(f"  ★ best OOD kNN: {best_knn:.4f}")
            else:
                patience -= 1
        logs["knn"].append(knn_ood)
        logs["knn_id"].append(knn_id)

        torch.save({
            "epoch": ep, "step": step,
            "online": model.online.state_dict(),
            "target": model.target.state_dict(),
            "optimizer": opt.state_dict(), "scaler": scaler.state_dict(),
            "best_knn": best_knn, "patience_left": patience, "ema_d": model.ema_d,
        }, resume_path)
        with open(out / "ssl_logs.json", "w") as f:
            json.dump(logs, f, indent=2)

        if patience <= 0:
            print("Early stopping SSL")
            break

    return logs, best_knn


