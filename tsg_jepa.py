UMAP_SAMPLES_PER_SPLIT = 3000

# Test data is used only for descriptive visualisation after
# final testing. It is not used for model selection or training.
UMAP_INCLUDE_TEST = True


def make_umap():
    sources = [
        ("ID val", id_val_ds),
        ("OOD val", ood_val_ds),
    ]

    if UMAP_INCLUDE_TEST:
        sources.append(("OOD test", ood_test_ds))

    fields = list(wilds_dataset.metadata_fields)

    hospital_name = next(
        (
            name
            for name in ("hospital", "center")
            if name in fields
        ),
        None,
    )

    if hospital_name is None:
        raise ValueError(
            f"Hospital metadata field not found: {fields}"
        )

    hospital_col = fields.index(hospital_name)

    features = []
    frames = []

    clf_model.eval()

    for split_name, dataset in sources:
        indices = np.random.RandomState(
            ANALYSIS_SEED
        ).choice(
            len(dataset),
            min(UMAP_SAMPLES_PER_SPLIT, len(dataset)),
            replace=False,
        )

        subset = dataset.subset

        centers = subset.metadata_array[
            indices, hospital_col
        ].cpu().numpy()

        expected_labels = subset.y_array[
            indices
        ].cpu().numpy().reshape(-1)

        batch_features = []
        batch_labels = []

        with torch.inference_mode():
            loader = analysis_loader(dataset, indices)

            for x, y in tqdm(
                loader,
                desc=f"UMAP {split_name}",
            ):
                x = x.to(device).contiguous(
                    memory_format=torch.channels_last
                )

                fmap = clf_model.encoder.features(x)
                z = clf_model.encoder.multi_scale_pool(fmap)

                batch_features.append(
                    z.float().cpu().numpy()
                )

                batch_labels.append(y.numpy())

        labels = np.concatenate(batch_labels)

        if not np.array_equal(labels, expected_labels):
            raise ValueError(
                "Image labels and hospital metadata "
                "are misaligned."
            )

        features.append(
            np.concatenate(batch_features)
        )

        frames.append(
            pd.DataFrame({
                "split": split_name,
                "subset_index": indices,
                "class": labels.astype(int),
                "hospital": centers.astype(int),
            })
        )

    features = np.concatenate(features).astype(
        np.float32
    )

    frame = pd.concat(frames, ignore_index=True)

    reducer = umap.UMAP(
        n_neighbors=min(30, len(features) - 1),
        min_dist=0.3,
        metric="cosine",
        random_state=ANALYSIS_SEED,
        n_jobs=1,
        low_memory=True,
    )

    # Labels are not passed into UMAP
    embedding = reducer.fit_transform(features)

    frame["umap_1"] = embedding[:, 0]
    frame["umap_2"] = embedding[:, 1]

    fig, axes = plt.subplots(
        1, 3, figsize=(17, 5)
    )

    for ax, column, title in zip(
        axes,
        ("class", "hospital", "split"),
        ("By class", "By hospital", "By split"),
    ):
        values = sorted(frame[column].unique())

        for i, value in enumerate(values):
            mask = frame[column].to_numpy() == value

            if column == "class":
                label = (
                    "Normal" if value == 0 else "Tumour"
                )
            elif column == "hospital":
                label = f"Hospital {value}"
            else:
                label = str(value)

            ax.scatter(
                embedding[mask, 0],
                embedding[mask, 1],
                s=4,
                alpha=0.45,
                color=plt.get_cmap("tab10")(i),
                label=label,
            )

        ax.set_title(title)
        ax.set_xticks([])
        ax.set_yticks([])
        ax.legend(
            markerscale=3,
            fontsize=9,
            frameon=False,
        )

    fig.suptitle(
        f"TSG-JEPA seed {cfg.seed} — "
        "saved best classifier"
    )

    fig.text(
        0.5,
        0.01,
        "Descriptive 2D projection; clustering does "
        "not prove domain invariance.",
        ha="center",
        fontsize=9,
    )

    fig.tight_layout(
        rect=(0, 0.04, 1, 0.94)
    )

    fig.savefig(
        analysis_dir / "umap_embeddings.png",
        dpi=220,
        bbox_inches="tight",
    )

    frame.to_csv(
        analysis_dir / "umap_points.csv",
        index=False,
    )

    np.savez_compressed(
        analysis_dir / "umap_features.npz",
        features=features,
        embedding=embedding,
    )

    with open(
        analysis_dir / "umap_protocol.json",
        "w",
    ) as f:
        json.dump(
            {
                "training_seed_declared": int(cfg.seed),
                "analysis_seed": ANALYSIS_SEED,
                "checkpoint_sha256": checkpoint_sha256,
                "feature_stage": (
                    "encoder.multi_scale_pool "
                    "before projection"
                ),
                "sample_count": int(len(frame)),
                "includes_test": UMAP_INCLUDE_TEST,
                "umap_version": (
                    importlib.metadata.version(
                        "umap-learn"
                    )
                ),
                "metric": "cosine",
                "min_dist": 0.3,
                "n_neighbors": reducer.n_neighbors,
                "label_usage": (
                    "plot colours only; joint "
                    "unsupervised fit on displayed splits"
                ),
            },
            f,
            indent=2,
        )

    plt.show()
    plt.close(fig)

    print(
        "Saved UMAP figure, coordinates and "
        f"features to {analysis_dir}"
    )


