class SpikeGateV2(nn.Module):
    def __init__(self, ch, tau=2.0, vth=0.5, steps=1, floor=0.5, beta_init=5.0):
        super().__init__()
        self.norm = gn(ch)
        self.vth = nn.Parameter(torch.full((1, ch, 1, 1), vth))
        self.beta = nn.Parameter(torch.tensor(beta_init))
        self.floor = floor
        self.fr = None

    def forward(self, x):
        sp = torch.sigmoid(self.beta * (self.norm(x) - self.vth))
        if self.training:
            self.fr = sp.detach().mean()
        return x * (self.floor + (1.0 - self.floor) * sp)


class DropPath(nn.Module):
    def __init__(self, p=0.0):
        super().__init__()
        self.p = float(p)

    def forward(self, x):
        if self.p == 0.0 or not self.training:
            return x
        keep = 1.0 - self.p
        mask = x.new_empty((x.shape[0],) + (1,) * (x.ndim - 1)).bernoulli_(keep)
        return x * mask / keep


class SqueezeExcite(nn.Module):
    def __init__(self, ch, rd=0.25):
        super().__init__()
        hid = max(8, int(ch * rd))
        self.net = nn.Sequential(
            nn.AdaptiveAvgPool2d(1),
            nn.Conv2d(ch, hid, 1), nn.GELU(),
            nn.Conv2d(hid, ch, 1), nn.Sigmoid())

    def forward(self, x):
        return x * self.net(x)

